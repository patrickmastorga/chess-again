use chess_again::core::Board;

/// Runs `board.perft` for each FEN and expected `(depth, nodes)` pair.
/// Sparse source entries such as D4-D6 retain their original depths.
fn assert_perft(fen: &str, expected: &[(u32, u64)]) {
    let mut board = Board::from_fen(fen).expect("test FEN should be valid");
    for &(depth, expected_nodes) in expected.iter() {
        let nodes = board.perft(depth);
        assert_eq!(
            nodes, expected_nodes,
            "perft({depth}) mismatch for FEN {fen:?}: got {nodes}, expected {expected_nodes}"
        );
    }
}

